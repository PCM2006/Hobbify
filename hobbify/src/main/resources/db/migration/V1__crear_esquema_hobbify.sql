CREATE TABLE public.pagos (
    id_pago bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion bigint REFERENCES public.inscripciones ON DELETE RESTRICT,
    id_suscripcion bigint REFERENCES public.suscripciones ON DELETE RESTRICT,
    proveedor varchar(40) NOT NULL,
    cuenta_pasarela_ref varchar(140) NOT NULL,
    referencia_externa varchar(120),
    monto numeric(10,2) NOT NULL CHECK (monto > 0 AND monto <> 'NaN'::numeric),
    moneda char(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
    comision numeric(10,2) CHECK (comision >= 0 AND comision <> 'NaN'::numeric),
    metodo varchar(30),
    estado varchar(16) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'aprobado', 'rechazado', 'cancelado')),
    creado_en timestamptz NOT NULL DEFAULT now(),
    pagado_en timestamptz,
    CONSTRAINT pagos_un_solo_origen CHECK (num_nonnulls(id_inscripcion, id_suscripcion) = 1),
    CONSTRAINT pagos_referencia_unica UNIQUE (proveedor, cuenta_pasarela_ref, referencia_externa),
    CONSTRAINT pagos_datos_de_aprobacion CHECK (
        (estado = 'aprobado') = (pagado_en IS NOT NULL)
        AND (estado <> 'aprobado' OR nullif(btrim(referencia_externa), '') IS NOT NULL)
    )
);

