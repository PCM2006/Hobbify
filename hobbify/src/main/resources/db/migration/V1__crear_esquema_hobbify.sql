);

CREATE TABLE public.usuario_categoria (
    id_usuario bigint REFERENCES public.usuarios ON DELETE CASCADE,
    id_categoria bigint REFERENCES public.categorias ON DELETE CASCADE,
    PRIMARY KEY (id_usuario, id_categoria)
);

CREATE TABLE public.seguidos (
    id_usuario bigint REFERENCES public.usuarios ON DELETE CASCADE,
    id_empresa bigint REFERENCES public.empresas ON DELETE CASCADE,
    seguido_en timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id_usuario, id_empresa)
);

CREATE TABLE public.favoritos (
    id_usuario bigint REFERENCES public.usuarios ON DELETE CASCADE,
    id_publicacion bigint REFERENCES public.publicaciones ON DELETE CASCADE,
    guardado_en timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id_usuario, id_publicacion)
);

CREATE TABLE public.visitas_publicacion (
    id_visita bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion bigint NOT NULL REFERENCES public.publicaciones ON DELETE CASCADE,
    id_usuario bigint REFERENCES public.usuarios ON DELETE CASCADE,
    sesion_hash char(64),
    primera_visita_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT visitas_un_solo_identificador CHECK (num_nonnulls(id_usuario, sesion_hash) = 1)
);

CREATE TABLE public.inscripciones (
    id_inscripcion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario bigint NOT NULL REFERENCES public.usuarios ON DELETE RESTRICT,
    id_publicacion bigint NOT NULL REFERENCES public.publicaciones ON DELETE RESTRICT,
    estado varchar(18) NOT NULL DEFAULT 'pendiente_pago'
        CHECK (estado IN ('pendiente_pago', 'confirmada', 'cancelada')),
    importe_acordado numeric(10,2) NOT NULL,
    moneda char(3) CHECK (moneda ~ '^[A-Z]{3}$'),
    codigo_qr varchar(100) UNIQUE,
    creada_en timestamptz NOT NULL DEFAULT now(),
    confirmada_en timestamptz,
    CONSTRAINT inscripciones_usuario_publicacion UNIQUE (id_usuario, id_publicacion),
    CONSTRAINT inscripciones_importe_valido CHECK (
        importe_acordado >= 0 AND importe_acordado <> 'NaN'::numeric
        AND (importe_acordado = 0 OR moneda IS NOT NULL)
    ),
    CONSTRAINT inscripciones_fecha_confirmacion
        CHECK (estado <> 'confirmada' OR confirmada_en IS NOT NULL),
    CONSTRAINT inscripciones_qr_confirmado
        CHECK (codigo_qr IS NULL OR (estado = 'confirmada' AND btrim(codigo_qr) <> ''))
);

CREATE TABLE public.resenas (
    id_inscripcion bigint PRIMARY KEY REFERENCES public.inscripciones ON DELETE CASCADE,
    puntuacion smallint NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
    comentario text,
    creada_en timestamptz NOT NULL DEFAULT now()
