    creada_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.suscripciones (
    id_suscripcion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa bigint NOT NULL REFERENCES public.empresas ON DELETE RESTRICT,
    plan varchar(30) NOT NULL,
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL CHECK (fecha_fin > fecha_inicio),
    importe_acordado numeric(10,2) NOT NULL,
    moneda char(3) CHECK (moneda ~ '^[A-Z]{3}$'),
    estado varchar(16) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'activa', 'vencida', 'cancelada')),
    CONSTRAINT suscripciones_importe_valido CHECK (
        importe_acordado >= 0 AND importe_acordado <> 'NaN'::numeric
        AND (importe_acordado = 0 OR moneda IS NOT NULL)
    ),
    CONSTRAINT suscripciones_activas_sin_solape EXCLUDE USING gist (
        id_empresa WITH =,
        daterange(fecha_inicio, fecha_fin, '[)') WITH &&
    ) WHERE (estado = 'activa')
