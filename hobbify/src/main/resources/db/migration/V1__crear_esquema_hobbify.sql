-- Normalización del correo y del nombre de las categorías.
CREATE FUNCTION public.normalizar_datos_unicos()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'usuarios' THEN
        NEW.correo := lower(btrim(NEW.correo));
    ELSE
        NEW.nombre := lower(btrim(NEW.nombre));
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER usuarios_normalizar_correo
BEFORE INSERT OR UPDATE OF correo ON public.usuarios
FOR EACH ROW EXECUTE FUNCTION public.normalizar_datos_unicos();

CREATE TRIGGER categorias_normalizar_nombre
BEFORE INSERT OR UPDATE OF nombre ON public.categorias
FOR EACH ROW EXECUTE FUNCTION public.normalizar_datos_unicos();

-- Insertar la publicación y su detalle de lugar, taller o charla entre el mismo BEGIN y COMMIT.
CREATE FUNCTION public.comprobar_detalle_publicacion(ficha_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    ficha_tipo varchar(12);
    tiene_lugar boolean;
    tiene_taller boolean;
    tiene_charla boolean;
BEGIN
    SELECT p.tipo INTO ficha_tipo
    FROM public.publicaciones p
    WHERE p.id_publicacion = ficha_id
    FOR NO KEY UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT
        EXISTS (SELECT 1 FROM public.lugares WHERE id_publicacion = ficha_id),
        EXISTS (SELECT 1 FROM public.talleres WHERE id_publicacion = ficha_id),
        EXISTS (SELECT 1 FROM public.charlas WHERE id_publicacion = ficha_id)
    INTO tiene_lugar, tiene_taller, tiene_charla;

    IF tiene_lugar <> (ficha_tipo = 'lugar')
        OR tiene_taller <> (ficha_tipo = 'taller')
        OR tiene_charla <> (ficha_tipo = 'charla') THEN
        RAISE EXCEPTION 'La publicación % debe tener un solo detalle de tipo %', ficha_id, ficha_tipo
            USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION public.validar_detalle_publicacion()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'DELETE' THEN
        PERFORM public.comprobar_detalle_publicacion(NEW.id_publicacion);
    END IF;
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.id_publicacion <> NEW.id_publicacion) THEN
        PERFORM public.comprobar_detalle_publicacion(OLD.id_publicacion);
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER publicaciones_validar_detalle
AFTER INSERT OR UPDATE OF tipo, id_publicacion ON public.publicaciones
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION public.validar_detalle_publicacion();

CREATE CONSTRAINT TRIGGER lugares_validar_detalle
AFTER INSERT OR UPDATE OF id_publicacion OR DELETE ON public.lugares
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION public.validar_detalle_publicacion();

CREATE CONSTRAINT TRIGGER talleres_validar_detalle
AFTER INSERT OR UPDATE OF id_publicacion OR DELETE ON public.talleres
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION public.validar_detalle_publicacion();

CREATE CONSTRAINT TRIGGER charlas_validar_detalle
AFTER INSERT OR UPDATE OF id_publicacion OR DELETE ON public.charlas
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION public.validar_detalle_publicacion();

CREATE FUNCTION public.validar_jerarquia_categorias()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    padre bigint;
    visitadas bigint[] := ARRAY[NEW.id_categoria];
BEGIN
    SELECT c.id_padre INTO padre
    FROM public.categorias c WHERE c.id_categoria = NEW.id_categoria;

    WHILE padre IS NOT NULL LOOP
        IF padre = ANY (visitadas) THEN
            RAISE EXCEPTION 'La categoría % forma parte de un ciclo', NEW.id_categoria
                USING ERRCODE = '23514';
        END IF;
        visitadas := array_append(visitadas, padre);
        SELECT c.id_padre INTO padre
        FROM public.categorias c WHERE c.id_categoria = padre
        FOR NO KEY UPDATE;
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER categorias_sin_ciclos
AFTER INSERT OR UPDATE OF id_padre, id_categoria ON public.categorias
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION public.validar_jerarquia_categorias();

-- Preparación de inscripciones, manteniendo el importe acordado al registrarse.
CREATE FUNCTION public.preparar_inscripcion()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ficha public.publicaciones%ROWTYPE;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT * INTO ficha
        FROM public.publicaciones p WHERE p.id_publicacion = NEW.id_publicacion
        FOR NO KEY UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'La publicación % no existe', NEW.id_publicacion USING ERRCODE = '23503';
        END IF;
        IF ficha.estado <> 'publicada' OR ficha.inscripcion <> 'abierta' THEN
            RAISE EXCEPTION 'La publicación % no acepta inscripciones', NEW.id_publicacion
                USING ERRCODE = '23514';
        END IF;
        NEW.importe_acordado := ficha.precio;
        NEW.moneda := ficha.moneda;
        NEW.estado := CASE WHEN ficha.precio = 0 THEN 'confirmada' ELSE 'pendiente_pago' END;
        NEW.confirmada_en := NULL;
    ELSIF (NEW.id_usuario, NEW.id_publicacion, NEW.importe_acordado, NEW.moneda)
        IS DISTINCT FROM (OLD.id_usuario, OLD.id_publicacion, OLD.importe_acordado, OLD.moneda) THEN
        RAISE EXCEPTION 'El usuario, la publicación y el precio acordado de una inscripción son fijos'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.estado = 'confirmada' THEN
        IF NEW.importe_acordado > 0 AND NOT EXISTS (
            SELECT 1 FROM public.pagos p
            WHERE p.id_inscripcion = NEW.id_inscripcion AND p.estado = 'aprobado'
        ) THEN
            RAISE EXCEPTION 'La inscripción % requiere un pago aprobado', NEW.id_inscripcion
                USING ERRCODE = '23514';
        END IF;
        NEW.confirmada_en := coalesce(NEW.confirmada_en, now());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER inscripciones_preparar
BEFORE INSERT OR UPDATE ON public.inscripciones
FOR EACH ROW EXECUTE FUNCTION public.preparar_inscripcion();

-- Serializa las reservas de cupo con una actualización de la fila de publicación.
CREATE FUNCTION public.comprobar_cupo(ficha_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    limite integer;
    ocupados bigint;
BEGIN
    UPDATE public.publicaciones p
    SET cupo_maximo = p.cupo_maximo
    WHERE p.id_publicacion = ficha_id
    RETURNING p.cupo_maximo INTO limite;

    IF limite IS NULL THEN
        RETURN;
    END IF;

    SELECT count(*) INTO ocupados
    FROM public.inscripciones i
    WHERE i.id_publicacion = ficha_id AND (
        i.estado = 'confirmada'
        OR (i.estado = 'pendiente_pago' AND EXISTS (
            SELECT 1 FROM public.pagos p
            WHERE p.id_inscripcion = i.id_inscripcion AND p.estado = 'pendiente'
        ))
    );

    IF ocupados > limite THEN
        RAISE EXCEPTION 'La publicación % alcanzó el máximo de % cupos', ficha_id, limite
            USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION public.validar_cupo_publicacion()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM public.comprobar_cupo(NEW.id_publicacion);
    RETURN NULL;
END;
$$;

CREATE TRIGGER inscripciones_validar_cupo
AFTER INSERT OR UPDATE OF estado ON public.inscripciones
FOR EACH ROW WHEN (NEW.estado IN ('confirmada', 'pendiente_pago'))
EXECUTE FUNCTION public.validar_cupo_publicacion();

CREATE TRIGGER publicaciones_validar_cupo
AFTER UPDATE OF cupo_maximo ON public.publicaciones
FOR EACH ROW WHEN (NEW.cupo_maximo IS DISTINCT FROM OLD.cupo_maximo)
EXECUTE FUNCTION public.validar_cupo_publicacion();

CREATE FUNCTION public.validar_inscripcion_resena()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM public.inscripciones i
    WHERE i.id_inscripcion = NEW.id_inscripcion AND i.estado = 'confirmada'
    FOR NO KEY UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Se requiere una inscripción confirmada para publicar una reseña'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER resenas_requerir_inscripcion_confirmada
BEFORE INSERT OR UPDATE OF id_inscripcion ON public.resenas
FOR EACH ROW EXECUTE FUNCTION public.validar_inscripcion_resena();

CREATE FUNCTION public.validar_suscripcion()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE'
        AND (NEW.id_empresa, NEW.importe_acordado, NEW.moneda)
            IS DISTINCT FROM (OLD.id_empresa, OLD.importe_acordado, OLD.moneda)
        AND EXISTS (SELECT 1 FROM public.pagos WHERE id_suscripcion = OLD.id_suscripcion) THEN
        RAISE EXCEPTION 'La empresa y el precio acordado deben conservarse una vez iniciado un cobro'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.estado = 'activa' AND NEW.importe_acordado > 0 AND NOT EXISTS (
        SELECT 1 FROM public.pagos
        WHERE id_suscripcion = NEW.id_suscripcion AND estado = 'aprobado'
    ) THEN
        RAISE EXCEPTION 'La suscripción % requiere un pago aprobado', NEW.id_suscripcion
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER suscripciones_validar
BEFORE INSERT OR UPDATE ON public.suscripciones
FOR EACH ROW EXECUTE FUNCTION public.validar_suscripcion();

-- Un pago pendiente reserva cupo. Un pago aprobado confirma o activa su origen.
CREATE FUNCTION public.verificar_pago()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    importe_origen numeric(10,2);
    moneda_origen char(3);
    estado_origen varchar(18);
    proveedor_empresa varchar(40);
    cuenta_empresa varchar(140);
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado = 'aprobado' THEN
            RAISE EXCEPTION 'El cobro aprobado % pertenece al historial de pagos', OLD.id_pago
                USING ERRCODE = '23514';
        END IF;
        RETURN OLD;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF (NEW.id_inscripcion, NEW.id_suscripcion, NEW.proveedor, NEW.cuenta_pasarela_ref, NEW.monto, NEW.moneda)
            IS DISTINCT FROM
            (OLD.id_inscripcion, OLD.id_suscripcion, OLD.proveedor, OLD.cuenta_pasarela_ref, OLD.monto, OLD.moneda) THEN
            RAISE EXCEPTION 'El origen y el importe de un intento de cobro son fijos' USING ERRCODE = '23514';
        END IF;
        IF (OLD.estado <> 'pendiente' AND NEW.estado <> OLD.estado)
            OR (OLD.referencia_externa IS NOT NULL AND NEW.referencia_externa IS DISTINCT FROM OLD.referencia_externa)
            OR (OLD.estado = 'aprobado' AND NEW.pagado_en IS DISTINCT FROM OLD.pagado_en) THEN
            RAISE EXCEPTION 'El estado final y la referencia asignada al pago deben conservarse'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.estado = OLD.estado THEN
            RETURN NEW;
        END IF;
    END IF;

    IF num_nonnulls(NEW.id_inscripcion, NEW.id_suscripcion) <> 1 THEN
        RAISE EXCEPTION 'Cada pago corresponde a una inscripción o a una suscripción' USING ERRCODE = '23514';
    END IF;

    IF NEW.id_inscripcion IS NOT NULL THEN
        SELECT i.importe_acordado, i.moneda, i.estado, e.proveedor_pasarela, e.cuenta_pasarela_ref
        INTO importe_origen, moneda_origen, estado_origen, proveedor_empresa, cuenta_empresa
        FROM public.inscripciones i
        JOIN public.publicaciones p ON p.id_publicacion = i.id_publicacion
        JOIN public.empresas e ON e.id_usuario = p.id_empresa
        WHERE i.id_inscripcion = NEW.id_inscripcion
        FOR NO KEY UPDATE OF i;
    ELSE
        UPDATE public.suscripciones s SET estado = s.estado
        WHERE s.id_suscripcion = NEW.id_suscripcion
        RETURNING s.importe_acordado, s.moneda, s.estado
        INTO importe_origen, moneda_origen, estado_origen;
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El origen del pago no existe' USING ERRCODE = '23503';
    END IF;

    IF TG_OP = 'INSERT' AND NEW.id_inscripcion IS NOT NULL AND (
        NEW.proveedor IS DISTINCT FROM proveedor_empresa OR NEW.cuenta_pasarela_ref IS DISTINCT FROM cuenta_empresa
    ) THEN
        RAISE EXCEPTION 'El pago de la inscripción requiere la cuenta de pasarela de su empresa'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.monto IS DISTINCT FROM importe_origen OR NEW.moneda IS DISTINCT FROM moneda_origen THEN
        RAISE EXCEPTION 'El monto y la moneda del pago deben coincidir con los valores acordados'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.estado IN ('pendiente', 'aprobado') AND estado_origen <>
        (CASE WHEN NEW.id_inscripcion IS NOT NULL THEN 'pendiente_pago' ELSE 'pendiente' END) THEN
        RAISE EXCEPTION 'El origen de un cobro nuevo o aprobado debe estar pendiente'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.estado = 'aprobado' THEN
        NEW.pagado_en := coalesce(NEW.pagado_en, now());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER pagos_verificar
BEFORE INSERT OR UPDATE OR DELETE ON public.pagos
FOR EACH ROW EXECUTE FUNCTION public.verificar_pago();

CREATE FUNCTION public.aplicar_estado_pago()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ficha_id bigint;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.estado = OLD.estado THEN
        RETURN NULL;
    END IF;

    IF NEW.estado = 'aprobado' THEN
        IF NEW.id_inscripcion IS NOT NULL THEN
            UPDATE public.inscripciones SET estado = 'confirmada'
            WHERE id_inscripcion = NEW.id_inscripcion;
        ELSE
            UPDATE public.suscripciones SET estado = 'activa'
            WHERE id_suscripcion = NEW.id_suscripcion;
        END IF;
    ELSIF NEW.estado = 'pendiente' AND NEW.id_inscripcion IS NOT NULL THEN
        SELECT i.id_publicacion INTO ficha_id
        FROM public.inscripciones i WHERE i.id_inscripcion = NEW.id_inscripcion;
        PERFORM public.comprobar_cupo(ficha_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER pagos_aplicar_estado
AFTER INSERT OR UPDATE OF estado ON public.pagos
FOR EACH ROW EXECUTE FUNCTION public.aplicar_estado_pago();
