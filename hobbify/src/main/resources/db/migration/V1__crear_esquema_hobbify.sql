CREATE TABLE public.notificaciones (
    id_notificacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario bigint NOT NULL REFERENCES public.usuarios ON DELETE CASCADE,
    id_publicacion bigint REFERENCES public.publicaciones ON DELETE SET NULL,
    titulo varchar(140) NOT NULL,
    mensaje text NOT NULL,
