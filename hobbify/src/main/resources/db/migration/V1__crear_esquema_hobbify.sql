-- Esquema inicial de PostgreSQL. Flyway administra la transacción.
-- Crea las 17 tablas del diagrama en el esquema public.
-- btree_gist permite impedir que se solapen periodos activos de una empresa.
-- La aplicación comprueba el rol y la propiedad de los datos, y verifica la
-- respuesta de la pasarela antes de marcar un pago como aprobado.

SET LOCAL search_path TO pg_catalog, public;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;

CREATE TABLE public.usuarios (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    apellido varchar(120),
    correo varchar(254) NOT NULL UNIQUE CHECK (correo <> ''),
    contrasena_hash varchar(255) NOT NULL,
    telefono varchar(30),
    foto_url text,
    fecha_nacimiento date,
    ciudad varchar(100),
    estado varchar(14) NOT NULL DEFAULT 'activo'
        CHECK (estado IN ('activo', 'inactivo', 'bloqueado')),
    creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.empresas (
    id_usuario bigint PRIMARY KEY REFERENCES public.usuarios ON DELETE CASCADE,
    nombre_comercial varchar(140) NOT NULL,
    descripcion text,
    nit varchar(30) UNIQUE,
    logo_url text,
    portada_url text,
    color_principal char(7) CHECK (color_principal ~ '^#[0-9A-Fa-f]{6}$'),
    correo_publico varchar(254),
    telefono_publico varchar(30),
    sitio_web varchar(250),
    instagram_url text,
    facebook_url text,
    whatsapp varchar(30),
    verificada boolean NOT NULL DEFAULT false,
    proveedor_pasarela varchar(40),
    cuenta_pasarela_ref varchar(140),
    CONSTRAINT empresas_cuenta_pasarela_completa
        CHECK (num_nonnulls(proveedor_pasarela, cuenta_pasarela_ref) IN (0, 2))
);

CREATE TABLE public.publicaciones (
    id_publicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa bigint NOT NULL REFERENCES public.empresas ON DELETE RESTRICT,
    tipo varchar(12) NOT NULL CHECK (tipo IN ('lugar', 'taller', 'charla')),
    titulo varchar(160) NOT NULL,
    descripcion text NOT NULL,
    imagen_url text,
    destacada boolean NOT NULL DEFAULT false,
    estado varchar(12) NOT NULL DEFAULT 'borrador'
        CHECK (estado IN ('borrador', 'publicada', 'archivada')),
    inscripcion varchar(12) NOT NULL DEFAULT 'no_aplica'
        CHECK (inscripcion IN ('no_aplica', 'abierta', 'cerrada')),
    cupo_maximo integer CHECK (cupo_maximo > 0),
    precio numeric(10,2) NOT NULL DEFAULT 0,
    moneda char(3) CHECK (moneda ~ '^[A-Z]{3}$'),
    creada_en timestamptz NOT NULL DEFAULT now(),
    publicada_en timestamptz,
    CONSTRAINT publicaciones_precio_valido
        CHECK (precio >= 0 AND precio <> 'NaN'::numeric AND (precio = 0 OR moneda IS NOT NULL)),
    CONSTRAINT publicaciones_fecha_publicacion
        CHECK (estado <> 'publicada' OR publicada_en IS NOT NULL)
);

CREATE TABLE public.lugares (
    id_publicacion bigint PRIMARY KEY REFERENCES public.publicaciones ON DELETE CASCADE,
    ciudad varchar(100) NOT NULL,
    direccion varchar(255) NOT NULL,
    zona varchar(100),
    latitud numeric(9,6),
    longitud numeric(9,6),
    capacidad integer CHECK (capacidad > 0),
    horario text,
    CONSTRAINT lugares_coordenadas_validas CHECK (
        num_nonnulls(latitud, longitud) IN (0, 2)
        AND latitud BETWEEN -90 AND 90
        AND longitud BETWEEN -180 AND 180
    )
);

CREATE TABLE public.talleres (
    id_publicacion bigint PRIMARY KEY REFERENCES public.publicaciones ON DELETE CASCADE,
    id_lugar bigint REFERENCES public.lugares ON DELETE RESTRICT,
    inicio_en timestamptz NOT NULL,
    fin_en timestamptz CHECK (fin_en > inicio_en),
    modalidad varchar(12) NOT NULL CHECK (modalidad IN ('presencial', 'virtual', 'hibrida')),
    ubicacion text CHECK (btrim(ubicacion) <> ''),
    enlace_en_linea text CHECK (btrim(enlace_en_linea) <> ''),
    nivel varchar(50),
    CONSTRAINT talleres_modalidad_ubicacion CHECK (
        num_nonnulls(id_lugar, ubicacion) = CASE WHEN modalidad = 'virtual' THEN 0 ELSE 1 END
        AND (modalidad = 'presencial' OR enlace_en_linea IS NOT NULL)
    )
);

CREATE TABLE public.charlas (
    id_publicacion bigint PRIMARY KEY REFERENCES public.publicaciones ON DELETE CASCADE,
    id_lugar bigint REFERENCES public.lugares ON DELETE RESTRICT,
    inicio_en timestamptz NOT NULL,
    fin_en timestamptz CHECK (fin_en > inicio_en),
    modalidad varchar(12) NOT NULL CHECK (modalidad IN ('presencial', 'virtual', 'hibrida')),
    ubicacion text CHECK (btrim(ubicacion) <> ''),
    enlace_en_linea text CHECK (btrim(enlace_en_linea) <> ''),
    ponente varchar(120),
    CONSTRAINT charlas_modalidad_ubicacion CHECK (
        num_nonnulls(id_lugar, ubicacion) = CASE WHEN modalidad = 'virtual' THEN 0 ELSE 1 END
        AND (modalidad = 'presencial' OR enlace_en_linea IS NOT NULL)
    )
);

CREATE TABLE public.categorias (
    id_categoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_padre bigint REFERENCES public.categorias ON DELETE SET NULL,
    nombre varchar(80) NOT NULL UNIQUE CHECK (nombre <> ''),
